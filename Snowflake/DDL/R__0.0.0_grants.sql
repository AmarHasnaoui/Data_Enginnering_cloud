GRANT SELECT ON FUTURE TABLES IN DATABASE BRONZE TO ROLE INGEST_ROLE;

GRANT READ, WRITE ON ALL    STAGES IN DATABASE BRONZE TO ROLE INGEST_ROLE;
GRANT READ, WRITE ON FUTURE STAGES IN DATABASE BRONZE TO ROLE INGEST_ROLE;

GRANT CREATE TABLE, CREATE STAGE, CREATE PIPE ON ALL    SCHEMAS IN DATABASE BRONZE TO ROLE INGEST_ROLE;
GRANT CREATE TABLE, CREATE STAGE, CREATE PIPE ON FUTURE SCHEMAS IN DATABASE BRONZE TO ROLE INGEST_ROLE;

GRANT USAGE, OPERATE, MONITOR ON WAREHOUSE INGEST_WH TO ROLE INGEST_ROLE;

