-- Schéma TRANSFORMATION : TRANSFORM_ROLE doit pouvoir tout faire (créer ET piloter
-- tasks/procédures — TASK_RUN_DBT_ALL, TASK_EXPORT_GOLD_TO_S3, SP_EXPORT_GOLD_TO_S3),
-- pas seulement les créer comme le permettaient les GRANT au niveau DATABASE ci-dessus.
GRANT ALL PRIVILEGES ON SCHEMA SILVER.TRANSFORMATION TO ROLE TRANSFORM_ROLE;

GRANT ALL PRIVILEGES ON ALL    TASKS IN SCHEMA SILVER.TRANSFORMATION TO ROLE TRANSFORM_ROLE;
GRANT ALL PRIVILEGES ON FUTURE TASKS IN SCHEMA SILVER.TRANSFORMATION TO ROLE TRANSFORM_ROLE;

GRANT ALL PRIVILEGES ON ALL    PROCEDURES IN SCHEMA SILVER.TRANSFORMATION TO ROLE TRANSFORM_ROLE;
GRANT ALL PRIVILEGES ON FUTURE PROCEDURES IN SCHEMA SILVER.TRANSFORMATION TO ROLE TRANSFORM_ROLE;

-- Privilège de COMPTE (pas schéma/DB) : sans lui, une Task créée et RESUME tourne
-- "armée" mais ses exécutions planifiées ne partent jamais sous ce rôle.
-- Nécessite que le rôle exécutant ce script (GITHUB_ROLE) ait MANAGE GRANTS, sinon
-- à lancer une fois manuellement depuis ACCOUNTADMIN.
GRANT EXECUTE TASK ON ACCOUNT TO ROLE TRANSFORM_ROLE;

